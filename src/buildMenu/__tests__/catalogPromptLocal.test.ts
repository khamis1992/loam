import assert from 'node:assert/strict';
import test from 'node:test';
import { BUILD_KINDS, type BuildKind } from '../../../packages/shared/src/buildMenu.js';
import { arabicPromptTemplate, listProfiles, profileFor } from '../catalog.js';

const MODEL_CLAIM =
  /generated by|model[- ]generated|(?:ولّ?د|أنشأ|أنتج|كتب)(?:ه|ها|ته)?\s+نموذج|نموذج(?:اً|ا)?\s+(?:ولّ?د|أنشأ|أنتج|كتب)/i;

test('listProfiles stays nine cards and chatbot is not one of them', () => {
  const profiles = listProfiles();
  assert.equal(profiles.length, 9);
  assert.equal(new Set(profiles.map((profile) => profile.kind)).size, 9);
  assert.deepEqual(
    profiles.map((profile) => profile.kind),
    [...BUILD_KINDS],
  );
  assert.equal(
    profiles.some((profile) => (profile.kind as string) === 'chatbot'),
    false,
  );
  assert.throws(() => profileFor('chatbot' as BuildKind), /missing_requirement:chatbot/);
  assert.throws(() => arabicPromptTemplate('chatbot' as BuildKind), /missing_requirement:chatbot/);
});

test('each arabic prompt template is local and does not claim a model wrote it', () => {
  const profiles = listProfiles();
  assert.equal(profiles.length, 9);
  for (const profile of profiles) {
    const prompt = arabicPromptTemplate(profile.kind);
    assert.equal(typeof prompt, 'string', profile.kind);
    assert.equal(prompt instanceof Promise, false, profile.kind);
    assert.match(prompt, /[\u0600-\u06FF]/, profile.kind);
    assert.match(prompt, /قالب تعليمات محلي/, profile.kind);
    assert.equal(prompt.includes('https://'), false, profile.kind);
    assert.equal(prompt.includes('http://'), false, profile.kind);
    assert.equal(prompt.includes('mailto:'), false, profile.kind);
    assert.equal(/\bManus\b/i.test(prompt), false, profile.kind);
    assert.equal(MODEL_CLAIM.test(prompt), false, profile.kind);
  }
});
