/**
 * writeStoredBrief and recordPlanProvenance refuse an existing destination
 * whose nlink is greater than 1 before writeFileSync, and leave the outside
 * bytes unchanged. A new file still writes. The static Arabic prompt stays a
 * local template: plan.json records model false and does not present that
 * prompt as model output. Hard links use fs.linkSync. This file does not
 * create a symlink or junction, and it does not call a model provider.
 *
 * Run: node --import tsx --test --test-concurrency=1 --test-force-exit --test-reporter=tap src/buildMenu/__tests__/planProvenanceHardLink.test.ts
 */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { arabicPromptTemplate } from '../catalog.js';
import { kindPlanContract } from '../planGate.js';
import { recordPlanProvenance, writeStoredBrief } from '../planProvenance.js';

const LOCAL_BRIEF = 'صفحة محلية بلا عنوان بعيد';
const REPLACED_BRIEF = 'صفحة محلية محدّثة بلا عنوان بعيد';
const MODEL_CLAIM =
  /generated by|model[- ]generated|(?:ولّ?د|أنشأ|أنتج|كتب)(?:ه|ها|ته)?\s+نموذج|نموذج(?:اً|ا)?\s+(?:ولّ?د|أنشأ|أنتج|كتب)/i;

const provenanceSource = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'planProvenance.ts');
const routeSource = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'server', 'routes', 'buildMenu.ts');

function isUnsafe(error: unknown): boolean {
  return error instanceof Error && error.message === 'unsafe_path';
}

function isEperm(error: unknown): boolean {
  return error instanceof Error && 'code' in error && (error as NodeJS.ErrnoException).code === 'EPERM';
}

function withPair(prefix: string, run: (workspace: string, outside: string) => void): void {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  const workspace = path.join(root, 'project');
  const outside = path.join(root, 'outside');
  fs.mkdirSync(workspace);
  fs.mkdirSync(outside);
  try {
    run(workspace, outside);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

function briefPath(workspace: string): string {
  return path.join(workspace, '.loam', 'build-menu', 'brief.txt');
}

function planPath(workspace: string): string {
  return path.join(workspace, '.loam', 'build-menu', 'plan.json');
}

function destinationName(target: fs.PathLike): 'brief.txt' | 'plan.json' | null {
  const resolved = path.resolve(String(target));
  const normalized = process.platform === 'win32' ? resolved.toLowerCase() : resolved;
  const marker = `${path.sep}.loam${path.sep}build-menu${path.sep}`;
  const suffix = process.platform === 'win32' ? marker.toLowerCase() : marker;
  if (normalized.endsWith(`${suffix}brief.txt`)) return 'brief.txt';
  if (normalized.endsWith(`${suffix}plan.json`)) return 'plan.json';
  return null;
}

function plantLink(outside: string, destination: string, bytes: Buffer): string {
  const outsideFile = path.join(outside, path.basename(destination));
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(outsideFile, bytes);
  fs.linkSync(outsideFile, destination);
  return outsideFile;
}

function assertLinked(destination: string, outsideFile: string): void {
  const stat = fs.lstatSync(destination);
  assert.equal(stat.isSymbolicLink(), false);
  assert.equal(stat.isFile(), true);
  assert.equal(stat.nlink > 1, true);
  const linked = fs.lstatSync(outsideFile);
  assert.equal(linked.isSymbolicLink(), false);
  assert.equal(linked.isFile(), true);
  assert.equal(linked.nlink > 1, true);
  assert.equal(stat.ino, linked.ino);
}

function assertPlain(file: string): void {
  const stat = fs.lstatSync(file);
  assert.equal(stat.isSymbolicLink(), false);
  assert.equal(stat.isFile(), true);
  assert.equal(stat.nlink, 1);
}

test('plan provenance checks both writes and does not call a model provider', () => {
  const source = fs.readFileSync(provenanceSource, 'utf8');
  assert.equal((source.match(/writeFileSync/g) ?? []).length, 2);
  assert.equal((source.match(/stat\.nlink > 1/g) ?? []).length, 3);
  assert.equal(source.includes('catch'), false);
  assert.equal(source.includes('symlink'), false);
  assert.equal(source.includes('junction'), false);
  assert.equal(source.includes('arabicPromptTemplate'), false);
  assert.equal(/openai|anthropic|generateText|chat\.completions|fetch\(/i.test(source), false);
  const route = fs.readFileSync(routeSource, 'utf8');
  const start = route.indexOf("if (p.endsWith('/plan'))");
  const end = route.indexOf('try {', start);
  assert.equal(start >= 0, true);
  assert.equal(end > start, true);
  const branch = route.slice(start, end);
  assert.match(branch, /generation needs a model provider/);
  assert.equal(branch.includes('arabicPromptTemplate'), false);
  assert.equal(branch.includes('قالب تعليمات'), false);
});

test('an existing brief or plan with nlink greater than 1 is refused before write', () => {
  withPair('loam-46-plan-link-', (workspace, outside) => {
    const brief = briefPath(workspace);
    const plan = planPath(workspace);
    const briefBytes = Buffer.from('outside brief bytes\n');
    const planBytes = Buffer.from('{"outside":true}\n');
    const outsideBrief = plantLink(outside, brief, briefBytes);
    const outsidePlan = plantLink(outside, plan, planBytes);
    assertLinked(brief, outsideBrief);
    assertLinked(plan, outsidePlan);
    assert.throws(() => writeStoredBrief(workspace, LOCAL_BRIEF), isUnsafe);
    assert.throws(() => recordPlanProvenance(workspace, 'website'), isUnsafe);
    assert.deepEqual(fs.readFileSync(brief), briefBytes);
    assert.deepEqual(fs.readFileSync(outsideBrief), briefBytes);
    assert.deepEqual(fs.readFileSync(plan), planBytes);
    assert.deepEqual(fs.readFileSync(outsidePlan), planBytes);
    assertLinked(brief, outsideBrief);
    assertLinked(plan, outsidePlan);
  });
});

test('a new brief and plan still write and the static Arabic prompt is not model output', () => {
  const prompt = arabicPromptTemplate('website');
  assert.equal(typeof prompt, 'string');
  assert.equal(prompt instanceof Promise, false);
  assert.match(prompt, /قالب تعليمات محلي ثابت/);
  assert.equal(MODEL_CLAIM.test(prompt), false);
  withPair('loam-46-plan-new-', (workspace) => {
    const brief = briefPath(workspace);
    const plan = planPath(workspace);
    assert.equal(fs.existsSync(brief), false);
    assert.equal(fs.existsSync(plan), false);
    assert.equal(writeStoredBrief(workspace, LOCAL_BRIEF), undefined);
    assert.equal(recordPlanProvenance(workspace, 'website'), undefined);
    assertPlain(brief);
    assertPlain(plan);
    assert.equal(fs.readFileSync(brief, 'utf8'), `${LOCAL_BRIEF}\n`);
    const contract = kindPlanContract('website');
    const planText = fs.readFileSync(plan, 'utf8');
    const saved = JSON.parse(planText) as { source: string; model: boolean; brief: string; userBriefSha256: string | null };
    assert.equal(saved.source, 'loam');
    assert.equal(saved.model, false);
    assert.equal(saved.brief, contract.brief);
    assert.equal(saved.userBriefSha256, createHash('sha256').update(LOCAL_BRIEF).digest('hex'));
    assert.equal(planText.includes(prompt), false);
    assert.equal(planText.includes(LOCAL_BRIEF), false);
    assert.equal(MODEL_CLAIM.test(planText), false);
    assert.equal(MODEL_CLAIM.test(saved.brief), false);
    assert.equal(writeStoredBrief(workspace, REPLACED_BRIEF), undefined);
    assert.equal(recordPlanProvenance(workspace, 'website'), undefined);
    assertPlain(brief);
    assertPlain(plan);
    assert.equal(fs.readFileSync(brief, 'utf8'), `${REPLACED_BRIEF}\n`);
    const replaced = JSON.parse(fs.readFileSync(plan, 'utf8')) as { model: boolean; brief: string; userBriefSha256: string | null };
    assert.equal(replaced.model, false);
    assert.equal(replaced.brief, contract.brief);
    assert.equal(replaced.userBriefSha256, createHash('sha256').update(REPLACED_BRIEF).digest('hex'));
  });
});

function refuseLstat(name: 'brief.txt' | 'plan.json', run: () => void): void {
  const realLstatSync = fs.lstatSync;
  let calls = 0;
  fs.lstatSync = ((target: fs.PathLike, options?: Parameters<typeof fs.lstatSync>[1]) => {
    if (destinationName(target) === name) {
      calls += 1;
      const error = new Error('operation not permitted') as NodeJS.ErrnoException;
      error.code = 'EPERM';
      throw error;
    }
    return realLstatSync(target, options);
  }) as typeof fs.lstatSync;
  try {
    assert.throws(run, isEperm);
    assert.equal(calls > 0, true);
  } finally {
    fs.lstatSync = realLstatSync;
  }
}

test('lstat EPERM is not swallowed before either write', () => {
  withPair('loam-46-plan-eperm-', (workspace) => {
    const brief = briefPath(workspace);
    const plan = planPath(workspace);
    const briefBytes = Buffer.from('ملاحظة سابقة\n');
    const planBytes = Buffer.from('{"kept":true}\n');
    fs.mkdirSync(path.dirname(brief), { recursive: true });
    fs.writeFileSync(brief, briefBytes);
    fs.writeFileSync(plan, planBytes);
    assertPlain(brief);
    assertPlain(plan);
    refuseLstat('brief.txt', () => writeStoredBrief(workspace, LOCAL_BRIEF));
    refuseLstat('plan.json', () => recordPlanProvenance(workspace, 'website'));
    assertPlain(brief);
    assertPlain(plan);
    assert.deepEqual(fs.readFileSync(brief), briefBytes);
    assert.deepEqual(fs.readFileSync(plan), planBytes);
  });
});
