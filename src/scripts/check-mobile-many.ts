import {tools,more} from './mobile-builder-test.js';
import assert from 'node:assert/strict';
import type { Browser } from 'playwright';
import JSZip from 'jszip';
import { transform } from 'esbuild';
import { manyPageProject } from './mobile-many-fixture.js';
import { validateProject } from '../mobile/store.js';

export async function checkManyPages(browser: Browser, base: string) {
  const project = manyPageProject();
  assert.equal(validateProject(project).screens.length,40);
  assert.equal(validateProject({...project,history:{ignored:'x'.repeat(3_000_000)}}).screens.length,40);
  const invalid=(mutate:(p:typeof project)=>void,pattern:RegExp)=>{const p=structuredClone(project);mutate(p);assert.throws(()=>validateProject(p),pattern);};
  invalid(p=>{p.screens[1]!.parentId='missing';},/does not exist/);
  invalid(p=>{p.screens[1]!.parentId=p.screens[7]!.id;},/cycle/);
  invalid(p=>{p.screens[1]!.kind='primary';delete p.screens[1]!.parentId;},/1 and 5/);
  invalid(p=>{p.screens=Array.from({length:101},()=>p.screens[0]!);},/1 and 100/);
  const post=async(url:string,body:unknown)=>{const r=await fetch(base+url,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body)});assert.ok(r.ok,await r.clone().text());return r.json() as Promise<{task:{id:string}}>;};
  const {task}=await post('/api/tasks/draft',{mode:'build',title:project.title});
  await post('/api/mobile',{taskId:task.id,project,expectedRevision:0});
  const page=await browser.newPage({viewport:{width:1110,height:884}}),errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
  await page.goto(base+'/mobile.html?taskId='+task.id);
  const app=page.frameLocator('#preview');
  await page.locator('#open-explorer').filter({hasText:'40'}).waitFor();
  await app.locator('nav button').first().waitFor();
  assert.equal(await app.locator('nav button').count(),5);
  await page.locator('#open-explorer').click();
  assert.equal(await page.locator('.screen-group').count(),5);
  await page.locator('#screen-search').fill('الحساب 7');
  assert.equal(await page.locator('#screen-list [data-screen-id]').count(),1);
  await page.getByRole('button',{name:'تفضيل الحساب 7',exact:true}).click();
  await page.locator('#screen-list [data-screen-id="section4_page7"]').click();
  await app.locator('h1').filter({hasText:'الحساب 7'}).waitFor();
  assert.match(await page.locator('#screen-path').innerText(),/الحساب 1/);
  await app.getByRole('button',{name:'رجوع',exact:true}).click();
  await app.locator('h1').filter({hasText:'الحساب 1'}).waitFor();
  await page.locator('#open-explorer').click();await page.locator('[data-screen-filter="favorite"]').click();
  assert.equal(await page.locator('#screen-list [data-screen-id]').count(),1);
  await page.locator('[data-screen-filter="recent"]').click();assert.ok(await page.locator('#screen-list [data-screen-id]').count()>=2);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#screen-explorer').evaluate(n=>(n as unknown as {open:boolean}).open),false);
  await app.getByRole('button',{name:'المكتبة',exact:true}).click();
  await app.getByRole('button',{name:'افتح المكتبة 1',exact:true}).click();
  await app.getByLabel('ملاحظة المكتبة 1').fill('بيانات محفوظة أثناء التنقل');
  await app.getByRole('button',{name:'افتح التفاصيل المتقدمة',exact:true}).click();
  await app.getByRole('button',{name:'انتقل إلى الحساب 7',exact:true}).click();
  await app.getByRole('button',{name:'رجوع',exact:true}).click();
  await app.locator('h1').filter({hasText:'المكتبة 7'}).waitFor();
  await app.getByRole('button',{name:'رجوع',exact:true}).click();
  assert.equal(await app.getByLabel('ملاحظة المكتبة 1').inputValue(),'بيانات محفوظة أثناء التنقل');
  await tools(page,false);await more(page,'open-flow');
  assert.equal(await page.locator('.flow-node').count(),40);
  assert.match(await page.locator('#flow-summary').innerText(),/كل الصفحات لها مسار وصول/);
  await page.locator('#flow-section').selectOption('section4');assert.equal(await page.locator('.flow-node').count(),8);
  await page.locator('.flow-node[data-screen-id="section4_page7"] .flow-screen').click();
  await app.locator('h1').filter({hasText:'الحساب 7'}).waitFor();
  await page.locator('#screen-path a').filter({hasText:'الحساب 1'}).click();
  await tools(page,true);await page.locator('#screen-settings > summary').click();await page.locator('#delete-screen').click();
  assert.match(await page.locator('#open-explorer').innerText(),/39/);
  await tools(page,false);await more(page,'open-flow');assert.match(await page.locator('#flow-summary').innerText(),/كل الصفحات لها مسار وصول/);
  assert.match(await page.locator('.flow-node[data-screen-id="section4_page7"] .flow-parent').innerText(),/رجوع إلى الحساب$/);
  await page.locator('#close-flow').click();await page.locator('#undo').click();
  assert.match(await page.locator('#open-explorer').innerText(),/40/);
  await more(page,'add-screen');await tools(page,false);await more(page,'open-flow');assert.match(await page.locator('#flow-summary').innerText(),/1 صفحات بلا مسار/);await page.locator('#close-flow').click();await page.locator('#undo').click();
  await tools(page,true);await page.locator('#screen-group').fill('مجموعة مخصصة');await page.locator('#screen-title').focus();
  await tools(page,false);await page.locator('#save').click();await page.waitForFunction("document.querySelector('#status')?.textContent==='محفوظ على الجهاز'");
  await page.reload();await page.locator('#open-explorer').click();await page.locator('#screen-search').fill('مجموعة مخصصة');assert.equal(await page.locator('#screen-list [data-screen-id]').count(),1);
  await page.locator('#close-explorer').click();await page.locator('#undo').click();
  await tools(page,false);await more(page,'open-flow');await page.locator('#flow-section').selectOption('');
  for(const width of [1110,768,320]){await page.setViewportSize({width,height:884});assert.equal(await page.locator('html').evaluate(n=>n.scrollWidth>n.clientWidth+1),false);assert.equal(await page.locator('#flow-dialog').evaluate(n=>n.scrollWidth>n.clientWidth+1),false);}
  await page.setViewportSize({width:1110,height:884});await page.screenshot({path:'release/mobile-many-flow.png'});
  await page.locator('#close-flow').click();await page.locator('#open-explorer').click();await page.screenshot({path:'release/mobile-many-explorer.png'});
  const zip=await JSZip.loadAsync(await(await fetch(base+'/api/mobile/export?taskId='+task.id)).arrayBuffer());
  await transform(await zip.file('expo/App.js')!.async('string'),{loader:'jsx'});
  const html=await zip.file('index.html')!.async('string');await page.route('**/many-export',route=>route.fulfill({contentType:'text/html',body:html}));
  await page.goto(base+'/many-export');assert.equal(await page.locator('nav button').count(),5);
  await page.getByRole('button',{name:'افتح المكتبة 1',exact:true}).click();await page.getByRole('button',{name:'افتح التفاصيل المتقدمة',exact:true}).click();await page.getByRole('button',{name:'رجوع',exact:true}).click();assert.equal(await page.locator('h1').innerText(),'المكتبة 1');
  assert.deepEqual(errors,[]);await page.close();console.log('PASS 40 pages: groups/search/favorites/recent, breadcrumbs, nested/cross-section back, five primary tabs, storage, flow reachability, delete/reparent/undo, reload, responsive dialogs, exported web and Expo syntax');
}
