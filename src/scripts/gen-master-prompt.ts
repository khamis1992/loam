/**
 * Authoring-time generator for the master system prompt asset.
 *
 * Reads `prompts/loam-master.md` (the human-editable source of truth) and
 * emits `src/agent/masterPromptText.ts`, exporting MASTER_PROMPT_SECTIONS.
 * Sections are split on `## ` headings; the Appendix sections are kept as their
 * own entries so the assembler can append them in the order Appendix B requires.
 *
 * Run with: npm run gen:master-prompt
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..", "..");
const SOURCE = path.join(ROOT, "prompts", "loam-master.md");
const TARGET = path.join(ROOT, "src", "agent", "masterPromptText.ts");

export interface MasterPromptSection {
  id: string;
  title: string;
  body: string;
}

/** Stable machine id for a `## ` heading: its number, or an appendix slug. */
export function masterSectionId(title: string): string {
  const numbered = /^(\d+)\./.exec(title);
  if (numbered?.[1]) return numbered[1];
  if (/^Appendix A\b/i.test(title)) return "appendix-a";
  if (/^Appendix B\b/i.test(title)) return "appendix-b";
  return title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

/** Split a markdown document into `## ` sections (the H1 preamble is skipped). */
export function parseMasterSections(markdown: string): MasterPromptSection[] {
  const lines = markdown.replace(/\r\n/g, "\n").split("\n");
  const sections: MasterPromptSection[] = [];
  let current: { title: string; body: string[] } | null = null;
  for (const line of lines) {
    const heading = /^##\s+(.*\S)\s*$/.exec(line);
    if (heading) {
      if (current) sections.push({ id: masterSectionId(current.title), title: current.title, body: current.body.join("\n").trim() });
      current = { title: heading[1]!.trim(), body: [] };
    } else if (current) {
      current.body.push(line);
    }
  }
  if (current) sections.push({ id: masterSectionId(current.title), title: current.title, body: current.body.join("\n").trim() });
  return sections;
}

/** Render the TS module source for the parsed sections. */
export function generateMasterPromptTs(markdown: string): string {
  const sections = parseMasterSections(markdown);
  const header = [
    "// AUTO-GENERATED by src/scripts/gen-master-prompt.ts from prompts/loam-master.md.",
    "// Do not edit by hand. Regenerate with: npm run gen:master-prompt",
    "export interface MasterPromptSection {",
    "  id: string;",
    "  title: string;",
    "  body: string;",
    "}",
    "",
    "export const MASTER_PROMPT_SECTIONS: MasterPromptSection[] = [",
  ];
  const rows: string[] = [];
  for (const section of sections) {
    rows.push("  {");
    rows.push(`    id: ${JSON.stringify(section.id)},`);
    rows.push(`    title: ${JSON.stringify(section.title)},`);
    rows.push(`    body: ${JSON.stringify(section.body)},`);
    rows.push("  },");
  }
  const footer = ["];", "", ""];
  return [...header, ...rows, ...footer].join("\n");
}

function main(): void {
  if (!fs.existsSync(SOURCE)) {
    console.error(`missing prompt source: ${SOURCE}`);
    process.exit(1);
  }
  const markdown = fs.readFileSync(SOURCE, "utf8");
  const output = generateMasterPromptTs(markdown);
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, output, "utf8");
  const count = parseMasterSections(markdown).length;
  console.log(`generated ${TARGET} (${count} sections)`);
}

main();
