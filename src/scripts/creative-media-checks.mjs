import assert from 'node:assert/strict';
import fs from 'node:fs';
export async function checkCreativeMedia(page) {
    await page.locator('[data-media-open]').click();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const image = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 320; canvas.height = 180; const ctx = canvas.getContext('2d'); ctx.fillStyle = '#ff0000'; ctx.fillRect(0, 0, 320, 180); return canvas.toDataURL(); });
    await page.locator('[data-media-file]').setInputFiles({ name: 'red.png', mimeType: 'image/png', buffer: Buffer.from(image.split(',')[1], 'base64') });
    await page.waitForFunction(() => document.querySelector('[data-media-status]').textContent.startsWith('جاهز'));
    await page.locator('[data-media-field=grayscale]').fill('100');
    await page.locator('[data-media-field=ratio]').selectOption('square');
    await page.locator('[data-media-field=rotation]').selectOption('90');
    const pixel = await page.locator('.creative-media canvas').evaluate((el) => Array.from(el.getContext('2d').getImageData(5, 5, 1, 1).data));
    assert.equal(pixel[0], pixel[1]);
    assert.equal(pixel[1], pixel[2]);
    await page.locator('[data-media-field=text]').fill('Loam QA');
    const download = async (selector) => { const pending = page.waitForEvent('download'); await page.locator(selector).click(); return fs.readFileSync((await (await pending).path())); };
    const png = await download('[data-media-export]');
    assert.equal(png.readUInt32BE(16), 180);
    assert.equal(png.readUInt32BE(20), 180);
    const project = await download('[data-media-project]');
    const parsed = JSON.parse(project.toString());
    assert.equal(parsed.settings.grayscale, 100);
    assert.equal(parsed.settings.text, 'Loam QA');
    const saved = page.waitForResponse(r => r.url().includes('/api/upload?') && r.status() === 200);
    await page.locator('[data-media-save]').click();
    const savedResponse = await saved, savedFile = await savedResponse.json();
    assert.ok(savedFile.path.endsWith('loam-media.json'));
    const uploadURL = new URL(savedResponse.url());
    const persisted = await page.request.get(uploadURL.origin + '/api/media?taskId=' + uploadURL.searchParams.get('taskId') + '&path=' + encodeURIComponent(savedFile.path));
    assert.equal((await persisted.json()).settings.grayscale, 100);
    await page.locator('[data-media-field=grayscale]').fill('0');
    await page.locator('[data-media-file]').setInputFiles({ name: 'loam-media.json', mimeType: 'application/json', buffer: project });
    await page.waitForFunction(() => document.querySelector('[data-media-field=grayscale]').value === '100');
    await page.locator('[data-media-field=grayscale]').fill('0');
    await page.locator('[data-media-list]').click();
    await page.locator('[data-media-saved]').selectOption(savedFile.path);
    await page.waitForFunction(() => document.querySelector('[data-media-field=grayscale]').value === '100');
    const video = await page.evaluate(async () => {
        const canvas = document.createElement('canvas');
        canvas.width = 320;
        canvas.height = 180;
        const ctx = canvas.getContext('2d'), stream = canvas.captureStream(30);
        const audio = new AudioContext(), tone = audio.createOscillator(), output = audio.createMediaStreamDestination();
        tone.connect(output);
        tone.start();
        await audio.resume();
        stream.addTrack(output.stream.getAudioTracks()[0]);
        const recorder = new MediaRecorder(stream, { mimeType: 'video/webm;codecs=vp8,opus' }), chunks = [];
        recorder.ondataavailable = e => chunks.push(e.data);
        const ended = new Promise(resolve => recorder.onstop = () => resolve());
        let frame = 0;
        const timer = setInterval(() => { ctx.fillStyle = frame++ % 2 ? '#2288aa' : '#aa8822'; ctx.fillRect(0, 0, 320, 180); }, 30);
        recorder.start();
        await new Promise(r => setTimeout(r, 2200));
        recorder.stop();
        await ended;
        clearInterval(timer);
        tone.stop();
        stream.getTracks().forEach(t => t.stop());
        await audio.close();
        const { finalizeWebM } = await import('/creative-webm.js');
        const blob = await finalizeWebM(new Blob(chunks, { type: 'video/webm' }), 2.2);
        return await new Promise(resolve => { const reader = new FileReader(); reader.onload = () => resolve(String(reader.result)); reader.readAsDataURL(blob); });
    });
    await page.locator('[data-media-file]').setInputFiles({ name: 'clip.webm', mimeType: 'video/webm', buffer: Buffer.from(video.split(',')[1], 'base64') });
    await page.waitForFunction(() => document.querySelector('[data-media-status]').textContent.includes('clip.webm'));
    await page.locator('[data-media-field=start]').fill('0.3');
    await page.locator('[data-media-field=end]').fill('1.3');
    await page.locator('[data-media-field=brightness]').fill('120');
    const webm = await download('[data-media-export]');
    assert.equal(webm.subarray(0, 4).toString('hex'), '1a45dfa3');
    assert.ok(webm.length > 2000);
    await page.locator('[data-media-export]').waitFor({ state: 'visible' });
    await page.waitForFunction(() => !document.querySelector('[data-media-controls]').disabled);
    await page.locator('[data-media-file]').setInputFiles({ name: 'edited.webm', mimeType: 'video/webm', buffer: webm });
    await page.waitForFunction(() => document.querySelector('[data-media-status]').textContent.includes('edited.webm'));
    const duration = Number(await page.locator('[data-media-field=end]').inputValue());
    assert.ok(duration > .8 && duration < 1.2, 'trimmed WebM reopens with finite one-second duration');
    await page.locator('[data-media-field=muted]').check();
    const muted = await download('[data-media-export]');
    assert.ok(muted.length > 500);
    await page.waitForFunction(() => !document.querySelector('[data-media-controls]').disabled);
    let canceledDownload=false;const unexpected=()=>{canceledDownload=true;};page.on('download',unexpected);
    await page.locator('[data-media-export]').click();await page.locator('[data-media-cancel]').click();
    await page.waitForFunction(()=>document.querySelector('[data-media-status]').textContent.includes('أُلغي'));
    assert.equal(canceledDownload,false);page.off('download',unexpected);
    fs.mkdirSync('output/verification', { recursive: true });
    await page.screenshot({ path: 'output/verification/creative-media-editor.png' });
    const viewport=page.viewportSize();
    await page.setViewportSize({width:390,height:900});
    assert.equal(await page.locator('.creative-media').evaluate(el=>el.scrollWidth>el.clientWidth),false,'media dialog fits mobile width');
    if(viewport)await page.setViewportSize(viewport);
    await page.locator('[data-media-close]').click();
    assert.deepEqual(errors, []);
    console.log('PASS media UI: image crop/rotate/grayscale/text PNG, portable project save/upload/reimport, video with audio trim/effects WebM export/reimport and muted export');
    return {image,video};
}
