import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import sharp from 'sharp';
import { importStudio } from '../studio/import.js';
import { exportStudio } from '../studio/export.js';
import { validateStudio, saveStudio } from '../studio/store.js';
import { safeZip, part, first, all, serialize, P, A, R } from '../studio/ooxml.js';
import { renderSlidePreview } from '../studio/slide-preview.js';
const out='output/office-frontier';
const zip=await safeZip(await fs.readFile(out+'/original-picture-edited.pptx'));
const doc=await part(zip,'ppt/slides/slide1.xml'),pic=first(doc,P,'pic'),copy=pic.cloneNode(true);
first(copy,P,'cNvPr').setAttribute('id','900');
const off=first(first(copy,P,'spPr'),A,'off');off.setAttribute('x','400000');off.setAttribute('y','2500000');
first(doc,P,'spTree').appendChild(copy);
zip.file('ppt/slides/slide1.xml',serialize(doc));
const source=await zip.generateAsync({type:'nodebuffer'});
await fs.writeFile(out+'/picture-replace-source.pptx',source);
const work=await fs.mkdtemp(out+'/picture-replace-');let artifact=await importStudio(work,source,'shared-pictures.pptx',0);
if(artifact.kind!=='presentation')throw Error();
assert.deepEqual((await exportStudio(artifact,work)).buffer,source);
const replacement=await sharp(Buffer.from('<svg width="600" height="400" xmlns="http://www.w3.org/2000/svg"><rect width="600" height="400" fill="#f9e5b9"/><rect x="40" y="40" width="180" height="320" fill="#156b79"/><circle cx="420" cy="200" r="110" fill="#c94e39"/></svg>')).png().toBuffer();
await fs.writeFile(out+'/picture-replacement.png',replacement);
const picture=artifact.content.slides[0]!.sourcePictures![0]!;
picture.src='data:image/png;base64,'+replacement.toString('base64');
const validated=validateStudio(artifact);assert.equal((validated.content as any).slides[0].sourcePictures[0].src,picture.src);
artifact=saveStudio(work,artifact,1);
const result=await exportStudio(artifact,work),after=await safeZip(result.buffer),updated=all(await part(after,'ppt/slides/slide1.xml'),P,'pic');
assert.equal(serialize(first(updated[0],P,'spPr')),serialize(first(pic,P,'spPr')));
assert.equal(serialize(first(updated[0],A,'srcRect')),serialize(first(pic,A,'srcRect')));
assert.equal(serialize(updated[1]),serialize(copy),'second shared image must stay unchanged');
const oldId=first(pic,A,'blip').getAttributeNS(R,'embed'),newId=first(updated[0],A,'blip').getAttributeNS(R,'embed');assert.notEqual(newId,oldId);
const rels=await part(after,'ppt/slides/_rels/slide1.xml.rels'),rel=all(rels,'*','Relationship').find(r=>r.getAttribute('Id')===newId);assert.ok(rel);
const media='ppt/'+rel.getAttribute('Target').replace('../','');assert.ok(after.file(media));
const changed=new Set(['ppt/slides/slide1.xml','ppt/slides/_rels/slide1.xml.rels','ppt/presentation.xml','[Content_Types].xml']);
let preserved=0;for(const name of Object.keys(zip.files)){if(zip.files[name]!.dir||changed.has(name))continue;assert.deepEqual(await after.file(name)!.async('nodebuffer'),await zip.file(name)!.async('nodebuffer'));preserved++;}
await fs.writeFile(out+'/picture-replaced.pptx',result.buffer);
await fs.writeFile(out+'/picture-replaced-native.png',await renderSlidePreview(result.buffer,1));
for(const src of ['https://example.test/a.png','data:image/svg+xml;base64,PHN2Zz4=','data:image/png;base64,YWJj']){const bad=structuredClone(artifact);(bad.content as any).slides[0].sourcePictures[0].src=src;assert.throws(()=>validateStudio(bad));await assert.rejects(()=>exportStudio(bad,work));}
const reopened=await importStudio(await fs.mkdtemp(out+'/picture-replaced-import-'),result.buffer,'replaced.pptx',0);assert.equal((reopened.content as any).slides[0].sourcePictures.length,2);
await fs.writeFile(out+'/picture-replacement-result.json',JSON.stringify({sharedPicturePreserved:true,originalMediaPreserved:true,cropAndTransformPreserved:true,preservedParts:preserved,reimport:true},null,2));
console.log('PASS replacement, shared-media isolation, crop/rotation/flip/frame preservation, source validation and reimport');
