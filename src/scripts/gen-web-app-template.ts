/**
 * Authoring-time generator for the web-app starter template payload.
 *
 * Reads `templates/web-app/` (the human-editable source of truth) and emits
 * `src/tools/templates/webapp/webAppTemplate.ts`, exporting the ordered file
 * map that the `web_scaffold` tool copies into a task workspace. Bundling the
 * payload keeps the packaged server self-contained: the tool never reads a
 * runtime template directory, so `dist/server.cjs` works inside the asar.
 *
 * Run with: npm run gen:web-app-template
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..", "..");
const SOURCE = path.join(ROOT, "templates", "web-app");
const TARGET_DIR = path.join(ROOT, "src", "tools", "templates", "webapp");
const TARGET = path.join(TARGET_DIR, "webAppTemplate.ts");

/** Directories that must never be bundled into the generated payload. */
const SKIP_DIRS = new Set(["node_modules", "dist", "dist-ssr", ".git", ".screenshots"]);

export interface WebAppTemplateFile {
  path: string;
  content: string;
}

/** Recursively collect the template files as POSIX-relative paths, sorted. */
export function collectTemplateFiles(dir: string, prefix = ""): WebAppTemplateFile[] {
  const out: WebAppTemplateFile[] = [];
  const entries = fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name, "en"));
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      out.push(...collectTemplateFiles(path.join(dir, entry.name), prefix ? `${prefix}/${entry.name}` : entry.name));
      continue;
    }
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    out.push({ path: rel, content: fs.readFileSync(path.join(dir, entry.name), "utf8") });
  }
  return out;
}

/** Render the generated TypeScript module source for the collected files. */
export function generateWebAppTemplateTs(files: WebAppTemplateFile[]): string {
  const header = [
    "// AUTO-GENERATED by src/scripts/gen-web-app-template.ts from templates/web-app.",
    "// Do not edit by hand. Regenerate with: npm run gen:web-app-template",
    "export interface WebAppTemplateFile {",
    "  path: string;",
    "  content: string;",
    "}",
    "",
    "/** Ordered starter files (POSIX paths). Copied verbatim by web_scaffold. */",
    "export const WEB_APP_TEMPLATE_FILES: WebAppTemplateFile[] = [",
  ];
  const body = files.map((file) => `  { path: ${JSON.stringify(file.path)}, content: ${JSON.stringify(file.content)} },`);
  const footer = ["];", ""];
  return [...header, ...body, ...footer].join("\n");
}

export function main(): number {
  if (!fs.existsSync(SOURCE)) {
    console.error(`web-app template source not found: ${SOURCE}`);
    return 1;
  }
  const files = collectTemplateFiles(SOURCE);
  fs.mkdirSync(TARGET_DIR, { recursive: true });
  fs.writeFileSync(TARGET, generateWebAppTemplateTs(files), "utf8");
  console.log(`generated ${TARGET} (${files.length} files)`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exit(main());
}
