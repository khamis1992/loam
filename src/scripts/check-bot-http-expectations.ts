import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { loadConfig } from "../config.js";
import { verifyApplication, parseAppContract } from "../agent/appVerification.js";
import { AcceptanceGuard } from "../agent/acceptanceGuard.js";
import type { OllamaClient } from "../ollama.js";
const cfg = loadConfig(); cfg.workspace = fs.mkdtempSync(path.join(os.tmpdir(), "loam-http-expectations-"));
const manifest = path.join(cfg.workspace, "app-verification.json");
const contract = { entry: "index.html", runtime: { type: "node", entry: "server.mjs" }, scenarios: [{ name: "Overdraw rejected", expectedResponses: [{ method: "POST", path: "/api/withdraw", status: 409, count: 1 }], steps: [{ action: "click", selector: "#withdraw" }, { action: "textExact", selector: "#error", value: "Insufficient stock" }, { action: "textExact", selector: "#count", value: "7" }] }] };
const writeContract = () => fs.writeFileSync(manifest, JSON.stringify(contract)); writeContract();
fs.writeFileSync(path.join(cfg.workspace, "index.html"), '<!doctype html><meta name="viewport" content="width=device-width"><h1>Stock</h1><output id="count">7</output><button id="withdraw">Withdraw 99</button><p id="error"></p><script>withdraw.onclick=async()=>{await fetch("/api/withdraw",{method:"POST"});document.querySelector("#error").textContent="Insufficient stock"}</script>');
const service = (status: number) => fs.writeFileSync(path.join(cfg.workspace, "server.mjs"), `import http from 'node:http';import fs from 'node:fs';http.createServer((q,r)=>{if(q.url==='/api/withdraw'){r.statusCode=${status};r.end('{}');return}r.setHeader('content-type','text/html');r.end(fs.readFileSync('/app/index.html'))}).listen(3000,'127.0.0.1')`);
let visualCalls = 0;
const ollama = { chat: async () => { visualCalls++; return { content: '{"verdict":"pass","reason":"fixture visual approval","issues":[]}', model: "fixture", toolCalls: [], usage: { promptTokens: 1, completionTokens: 1, durationMs: 1 } }; } } as unknown as OllamaClient;
service(409);
const good = await verifyApplication({ cfg, ollama, request: "Reject overdraw without changing quantity" });
assert.equal(good.pass, true, JSON.stringify(good));
assert.equal(visualCalls, 1);
service(500);
const serverFailure = await verifyApplication({ cfg, ollama, request: "Reject overdraw" });
assert.equal(serverFailure.pass, false); assert.equal(visualCalls, 1);
service(200);
const missingRejection = await verifyApplication({ cfg, ollama, request: "Reject overdraw" });
assert.equal(missingRejection.pass, false, "UI error text cannot fake a required backend rejection"); assert.equal(visualCalls, 1);
service(409); contract.scenarios[0]!.expectedResponses[0]!.count = 2; writeContract();
const wrongCount = await verifyApplication({ cfg, ollama, request: "Two rejected operations" });
assert.equal(wrongCount.pass, false); assert.equal(visualCalls, 1);
contract.scenarios[0]!.expectedResponses[0]!.count = 1; writeContract();
const guard = new AcceptanceGuard(); guard.check(cfg.workspace);
contract.scenarios[0]!.expectedResponses[0]!.status = 400; writeContract();
assert.throws(() => guard.check(cfg.workspace), /Frozen acceptance/);
contract.scenarios[0]!.expectedResponses[0]!.status = 500;
assert.throws(() => parseAppContract(JSON.stringify(contract)), /Invalid expected HTTP/);
fs.mkdirSync("docs/evidence", { recursive: true });
fs.writeFileSync("docs/evidence/bot-http-expectations.json", JSON.stringify({ at: new Date().toISOString(), workspace: cfg.workspace, visualJudgment: "fixture; browser and Node backend are real", good, serverFailure, missingRejection, wrongCount }, null, 2));
console.log("PASS actual browser/backend: explicit 409 accepted, 500/missing rejection/wrong count rejected, acceptance changes blocked");
