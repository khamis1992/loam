import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import assert from "node:assert/strict";
import { loadConfig } from "../config.js";
import { OllamaClient } from "../ollama.js";
import { saveScene } from "../creative/store.js";
import { verifyCreative } from "../agent/creativeVerification.js";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "loam-scene-live-"));
const cfg = loadConfig(); cfg.workspace = root;
cfg.vision.model = process.env.LOAM_BOT_TEST_MODEL || "glm-5.3-flash:cloud";
const ollama = new OllamaClient(cfg.ollamaUrl);
saveScene(root, { version: 1, title: "سيارة رياضية حمراء كاملة", nodes: [{ id: "car", name: "هيكل سيارة كاملة مع أربع عجلات", type: "box", position: [0, 1, 0], rotation: [0, 0, 0], scale: [1, 1, 1], material: { color: "#ee3333", metalness: .1, roughness: .5 }, visible: true, spin: 0 }], environment: { background: "#111722", lightIntensity: 3, exposure: 1, grid: false }, camera: { position: [6, 4, 6], target: [0, 1, 0], fov: 45 }, duration: 10 }, 0);
const cube = await verifyCreative({ cfg, ollama, request: "اعرض مكعبًا أحمر بسيطًا واضحًا على خلفية داكنة. لا أطلب سيارة أو تفاصيل إضافية." });
const car = await verifyCreative({ cfg, ollama, request: "صمم سيارة حمراء واضحة المعالم لها أربع عجلات سوداء وسقف وزجاج؛ لا تكتف بكتلة مكعبة مسماة سيارة." });
fs.mkdirSync("docs/evidence", { recursive: true });
fs.writeFileSync("docs/evidence/bot-creative-live.json", JSON.stringify({ at: new Date().toISOString(), workspace: root, cube, car }, null, 2));
assert.equal(cube.pass, true, cube.reason);
assert.equal(car.pass, false, "same cube cannot certify a car just because labels claim it is one");
assert.ok(car.visual, "rejection must come from actual visual review, not an outage");
console.log("PASS real vision accepts the requested cube and rejects the same render as a car despite misleading labels");
