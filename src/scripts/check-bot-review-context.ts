import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { loadConfig } from "../config.js";
import { critiqueStep, formatExecutorMessage } from "../agent/verifier.js";
import { runOrchestratedAgent } from "../agent/orchestrator.js";
import { ToolRegistry } from "../tools/registry.js";
import type { ChatOptions, OllamaClient } from "../ollama.js";
const cfg = loadConfig(); cfg.workspace = fs.mkdtempSync(path.join(os.tmpdir(), "loam-review-context-"));
const tail = "THE_COMPLETE_FINAL_LIMITATION_AND_DELIVERY_SENTENCE";
const message = "Detailed result. ".repeat(400) + tail;
const reply = (verdict: string) => ({ model: "fixture", content: JSON.stringify({ verdict, reason: "checked", fixes: verdict === "revise" ? ["Clarify the last sentence"] : [] }), toolCalls: [], usage: { promptTokens: 1, completionTokens: 1, durationMs: 1 } });
const reader = { chat: async (o: ChatOptions) => { assert.ok(o.messages.at(-1)?.content.includes(message), "critic receives full actual result beyond character 3000"); return reply("pass"); } } as unknown as OllamaClient;
await critiqueStep({ cfg, ollama: reader, goal: "review", request: "review", step: { id: "s1", title: "review", instruction: "review", successCriteria: "complete" }, stepIndex: 0, totalSteps: 1, attempt: 1, maxAttempts: 2, workerText: message, trace: [] });
const long = "HEAD_MARKER" + "x".repeat(80_000) + tail;
const excerpt = formatExecutorMessage(long);
assert.ok(excerpt.includes("HEAD_MARKER") && excerpt.endsWith(tail));
assert.ok(excerpt.includes("middle characters omitted") && excerpt.includes("NOT cut off"));
assert.ok(excerpt.length < 33_000);
let workerCalls = 0, finalCalls = 0;
const model = { chat: async (o: ChatOptions) => {
  const system = o.messages[0]?.content ?? "";
  if (system.includes("planner role")) return { ...reply("pass"), content: JSON.stringify({ goal: "report", trivial: false, steps: [{ id: "s1", title: "report", instruction: "report", successCriteria: "complete report" }] }) };
  if (system.includes("ONE executed plan step")) return reply("pass");
  if (system.includes("COMPLETED task as a whole")) return reply(++finalCalls === 1 ? "revise" : "pass");
  workerCalls++;
  if (workerCalls === 2) assert.ok(o.messages.some(m => m.content.includes(tail)), "repair worker receives the original ending, not a cut-off draft");
  return { ...reply("pass"), content: workerCalls === 1 ? message : "Clarified final report" };
} } as unknown as OllamaClient;
const run = await runOrchestratedAgent({ cfg, ollama: model, tools: new ToolRegistry(), prompt: "Write a report", emit: () => {} });
assert.equal(run.verified, true); assert.equal(workerCalls, 2); assert.equal(finalCalls, 2);
console.log("PASS critic and repair receive actual message endings; oversized excerpts explicitly disclose omitted middle text");
