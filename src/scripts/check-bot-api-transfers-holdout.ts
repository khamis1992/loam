import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { loadConfig } from "../config.js";
import { verifyApplication } from "../agent/appVerification.js";
import type { OllamaClient } from "../ollama.js";
const source = path.resolve("output/verification/bot-transfers-initial-20261019");
const cfg = loadConfig(); cfg.workspace = fs.mkdtempSync(path.join(os.tmpdir(), "loam-api-transfers-holdout-"));
for (const file of ["index.html", "server.mjs"]) fs.copyFileSync(path.join(source, file), path.join(cfg.workspace, file));
const contract = { entry: "index.html", runtime: { type: "node", entry: "server.mjs" }, scenarios: [{ name: "Reject whitespace-only request id", steps: [{ action: "visible", selector: "#transfer" }], apiChecks: [{ requests: [{ method: "POST", path: "/api/transfers", body: JSON.stringify({ requestId: " ", from: "A", to: "B", quantity: 1 }) }], statuses: [400] }] }] };
fs.writeFileSync(path.join(cfg.workspace, "app-verification.json"), JSON.stringify(contract));
let visionCalls = 0;
const ollama = { chat: async () => { visionCalls++; throw new Error("must not reach visual review on API failure"); } } as unknown as OllamaClient;
const result = await verifyApplication({ cfg, ollama, request: "Reject whitespace-only identifiers before mutating stock" });
assert.equal(result.pass, false);
assert.equal(result.checks.length, 2);
assert.ok(result.checks.every(c => c.error?.includes("API group 0 mismatch") && c.api?.[0]?.status === 201));
assert.equal(visionCalls, 0);
for (const file of ["index.html", "server.mjs"]) assert.deepEqual(fs.readFileSync(path.join(cfg.workspace, file)), fs.readFileSync(path.join(source, file)));
fs.writeFileSync("docs/evidence/bot-api-transfers-holdout.json", JSON.stringify({ at: new Date().toISOString(), source, workspace: cfg.workspace, pass: true, meaning: "new gate rejects unchanged defective generated application; original trial remains failed", result }, null, 2));
console.log("PASS new API gate rejects unchanged generated transfer app accepting whitespace-only identifier on both viewports");
