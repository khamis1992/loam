import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import assert from "node:assert/strict";
import { loadConfig } from "../config.js";
import { saveScene } from "../creative/store.js";
import { verifyCreative, needsCreativeVerification } from "../agent/creativeVerification.js";
import type { OllamaClient, ChatOptions } from "../ollama.js";
import { verifyFinal } from "../agent/verifier.js";
const workspace = fs.mkdtempSync(path.join(os.tmpdir(), "loam-creative-verify-"));
const cfg = loadConfig(); cfg.workspace = workspace;
const scene = { version: 1, title: "Red cube", nodes: [{ id: "cube", name: "cube", type: "box", position: [0, 1, 0], rotation: [0, 0, 0], scale: [1, 1, 1], material: { color: "#ee3333", metalness: .1, roughness: .5 }, visible: true, spin: 0 }], environment: { background: "#111722", lightIntensity: 3, exposure: 1, grid: false }, camera: { position: [6, 4, 6], target: [0, 1, 0], fov: 45 }, duration: 10 };
saveScene(workspace, scene, 0);
assert.equal(needsCreativeVerification(workspace, []), true);
let calls = 0;
const model = (pass: boolean, change = false, expectedImages = 2) => ({ chat: async (o: ChatOptions) => {
  calls++;
  assert.equal(o.messages.filter(m => m.images?.length).length, expectedImages);
  assert.ok(o.messages.filter(m => m.images?.length).every(m => m.images![0]!.length > 1000));
  if (change) saveScene(workspace, { ...scene, title: "Changed during review" }, 1);
  return { content: JSON.stringify({ verdict: pass ? "pass" : "revise", reason: pass ? "Red cube visible" : "Box is not a car", issues: pass ? [] : ["Requested car has no recognizable wheels/body"] }), model: "visual-fixture", toolCalls: [], usage: { promptTokens: 1, completionTokens: 1, durationMs: 1 } };
} }) as unknown as OllamaClient;
const good = await verifyCreative({ cfg, ollama: model(true), request: "Create a simple red cube" });
assert.equal(good.pass, true, good.reason);
assert.equal(good.screenshots.length, 2);
const bad = await verifyCreative({ cfg, ollama: model(false), request: "Create a car" });
assert.equal(bad.pass, false);
let finalCalls = 0;
const integrated = (visualPass: boolean) => ({ chat: async (o: ChatOptions) => {
  if (o.messages[0]?.content.includes("verifier role")) { finalCalls++; return { content: JSON.stringify({ verdict: "pass", reason: "inspected", fixes: [], finalAnswer: "The red cube was rendered and visually checked." }), toolCalls: [], model: "fixture", usage: { promptTokens: 1, completionTokens: 1, durationMs: 1 } }; }
  return model(visualPass).chat(o);
} }) as unknown as OllamaClient;
const options = { cfg, request: "Create red cube", goal: "cube", finalText: "Will verify later", trace: [], completedSteps: [] };
const gated = await verifyFinal({ ...options, ollama: integrated(true) });
assert.equal(gated.verdict, "pass"); assert.match(gated.finalAnswer!, /visually checked/);
const blocked = await verifyFinal({ ...options, ollama: integrated(false) });
assert.equal(blocked.verdict, "revise"); assert.equal(finalCalls, 1, "text judge cannot override visual rejection");
let offlineCalls = 0;
const offline = { chat: async () => { offlineCalls++; throw new Error("HTTP 503"); } } as unknown as OllamaClient;
const unavailable = await verifyFinal({ ...options, ollama: offline });
assert.equal(unavailable.verdict, "revise"); assert.equal(offlineCalls, 2);
assert.ok(unavailable.fixes.some(f => f.includes("Preserve the scene") && f.includes("Do not change geometry")), "outage must not demand destructive geometry repair");
const changed = await verifyCreative({ cfg, ollama: model(true, true), request: "Create a simple red cube" });
assert.equal(changed.pass, false);
assert.match(changed.reason, /changed during verification/);
saveScene(workspace, { ...scene, nodes: scene.nodes.map(n => ({ ...n, visible: false })) }, 2);
const beforeEmpty = calls;
const empty = await verifyCreative({ cfg, ollama: model(true), request: "Visible cube" });
assert.equal(empty.pass, false);
assert.equal(calls, beforeEmpty, "empty scene rejected before visual judgment");
const positions = Buffer.from(new Float32Array([-1, 0, 0, 1, 0, 0, 0, 2, 0]).buffer);
const gltf = { asset: { version: "2.0" }, scene: 0, scenes: [{ nodes: [0] }], nodes: [{ mesh: 0 }], meshes: [{ primitives: [{ attributes: { POSITION: 0 }, material: 0 }] }], materials: [{ doubleSided: true, pbrMetallicRoughness: { baseColorFactor: [1, 0, 0, 1] } }], buffers: [{ byteLength: positions.length, uri: `data:application/octet-stream;base64,${positions.toString("base64")}` }], bufferViews: [{ buffer: 0, byteLength: positions.length }], accessors: [{ bufferView: 0, componentType: 5126, count: 3, type: "VEC3", min: [-1, 0, 0], max: [1, 2, 0] }] };
const raw = JSON.stringify(gltf), json = Buffer.from(raw + " ".repeat((4 - Buffer.byteLength(raw) % 4) % 4));
const header = Buffer.alloc(20); header.writeUInt32LE(0x46546c67, 0); header.writeUInt32LE(2, 4); header.writeUInt32LE(20 + json.length, 8); header.writeUInt32LE(json.length, 12); header.writeUInt32LE(0x4e4f534a, 16);
fs.writeFileSync(path.join(workspace, "triangle.glb"), Buffer.concat([header, json]));
saveScene(workspace, { ...scene, nodes: [{ ...scene.nodes[0], type: "model", asset: "triangle.glb", spin: .5 }] }, 3);
const imported = await verifyCreative({ cfg, ollama: model(true, false, 3), request: "Imported spinning triangle" });
assert.equal(imported.pass, true, imported.reason); assert.equal(imported.screenshots.length, 3);
fs.mkdirSync("docs/evidence", { recursive: true });
fs.writeFileSync("docs/evidence/bot-creative-verification.json", JSON.stringify({ at: new Date().toISOString(), workspace, good, bad, changed, empty, imported, visualModelIsFixture: true }, null, 2));
console.log("PASS actual studio renders reach visual gate; rejection, mutation and empty scene fail closed");
