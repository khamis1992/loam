import assert from 'node:assert/strict';import fs from 'node:fs';import path from 'node:path';import os from 'node:os';
import {scanWorkspaceRoutesAndRisks} from '../tools/pentest.js';
import {startAssessment,readAssessment,retestAssessment,assessmentReport} from '../security/assessments.js';
import {executionDiagnostics} from '../security/diagnostics.js';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'loam-source-coverage-'));
fs.writeFileSync(path.join(root,'valid.ts'),'db.query("SELECT 1");');
fs.writeFileSync(path.join(root,'broken.ts'),'db.query(');
fs.writeFileSync(path.join(root,'large.js'),' '.repeat(300001));
fs.writeFileSync(path.join(root,'invalid.ts'),Buffer.from([0xff,0xfe,0xfd]));
fs.writeFileSync(path.join(root,'app.py'),'print("test")');
const scanned=scanWorkspaceRoutesAndRisks(root);
assert.equal(scanned.filesScanned,3);assert.equal(scanned.coverage!.sqlAnalyzed,1);
assert.equal(scanned.coverage!.sqlParseErrors,1);assert.equal(scanned.coverage!.sqlUnsupported,1);
assert.equal(scanned.coverage!.oversized,1);assert.equal(scanned.coverage!.unreadable,1);assert.equal(scanned.coverage!.incomplete,true);
assert.equal(scanned.coverage!.warnings.length,3);
async function finish(id:string){for(let n=0;n<300;n++){const r=readAssessment(root,id);if(r.status!=='running')return r;await new Promise(r=>setTimeout(r,100));}throw Error('Timeout');}
const first=await finish(startAssessment(root,{includeSource:true}).id);
assert.equal(first.status,'partial');assert.ok(first.findings.some(f=>f.check==='source_coverage'&&f.verdict==='error'));
assert.equal(executionDiagnostics(first).modules.find(m=>m.id==='source')!.state,'incomplete');
assert.match(assessmentReport(root,first.id),/broken.ts/);
assert.match(assessmentReport(root,first.id),/تغطية تحليل المصدر/);
// Resolve the test fixture failures without deleting user files.
for(const file of ['broken.ts','large.js','invalid.ts'])fs.writeFileSync(path.join(root,file),'const ready = true;');
const repeated=await finish(retestAssessment(root,first.id,{authorized:true}).id);
assert.equal(repeated.status,'completed');assert.equal(repeated.scan!.coverage!.incomplete,false);
const deep=['const q0="SELECT "+input;',...Array.from({length:40},(_,i)=>`const q${i+1}=q${i};`),'db.query(q40);'].join('\n');
fs.writeFileSync(path.join(root,'deep.ts'),deep);
const limited=await finish(startAssessment(root,{includeSource:true}).id);
assert.equal(limited.status,'partial');assert.equal(limited.scan!.coverage!.sqlLimited,1);
assert.equal(limited.scan!.coverage!.sqlParseErrors,0);
assert.ok(limited.scan!.coverage!.warnings.some(w=>w.file==='deep.ts'&&w.reason.includes('expansion limit')));
assert.match(assessmentReport(root,limited.id),/expansion limit/);
assert.equal(executionDiagnostics(limited).modules.find(m=>m.id==='source')!.state,'incomplete');
fs.writeFileSync(path.join(root,'deep.ts'),'const q="SELECT 1"; db.query(q);');
const withinLimits=await finish(retestAssessment(root,limited.id,{authorized:true}).id);
assert.equal(withinLimits.status,'completed');assert.equal(withinLimits.scan!.coverage!.sqlLimited,0);
const capped=fs.mkdtempSync(path.join(os.tmpdir(),'loam-source-limit-'));
for(let i=0;i<200;i++)fs.writeFileSync(path.join(capped,`file${i}.ts`),'const x=1;');
assert.equal(scanWorkspaceRoutesAndRisks(capped).coverage!.limitReached,false);
fs.writeFileSync(path.join(capped,'overflow.ts'),'const x=1;');
const overflow=scanWorkspaceRoutesAndRisks(capped);
assert.equal(overflow.filesScanned,200);assert.equal(overflow.coverage!.limitReached,true);assert.equal(overflow.coverage!.incomplete,true);
assert.equal(scanWorkspaceRoutesAndRisks(path.join(capped,'missing')).coverage!.unreadable,1);
console.log('PASS: syntax/size/encoding failures, unsupported-language accounting, partial campaign/UI diagnostics, corrected-fixture retest, exact 200 versus 201 file boundary');
