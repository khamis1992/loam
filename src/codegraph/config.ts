export type AutoIndexPolicy = "manual" | "ask-on-first-open" | "always";

export interface CodeGraphConfig {
  /** Master switch. Default false until W1-W12 pass on Khamis's PC. */
  enabled: boolean;
  /** How a project becomes indexed the first time. */
  autoIndex: AutoIndexPolicy;
  /** After the first opt-in, keep the graph fresh automatically (incremental extract). */
  autoRefresh: boolean;
  /** Absolute project roots that may never be indexed (case-insensitive on Windows). */
  denyRoots: string[];
  /** Extra exclude globs appended after DEFAULT_EXCLUDES (graphify --exclude syntax, anchored at the scan root). */
  extraExcludes: string[];
  /** Code files larger than this are excluded (graphify has no code-size cap — OBSERVED OOM on 17 MB bundles). */
  maxCodeFileBytes: number;
  /** Refuse to index when more than this many candidate code files remain after excludes. */
  maxCodeFiles: number;
  /** graphify --max-workers. Each worker peaked near 1.5 GB on pathological input; 4 keeps a normal repo under 0.7 GB. */
  maxWorkers: number;
  /** Kill the extract process tree after this long. */
  indexTimeoutMs: number;
  /** Debounce between the last Loam file write and an automatic incremental refresh. */
  refreshDebounceMs: number;
  /** A graph older than this is reported stale even without a HEAD move (catches edits made outside Loam). */
  maxGraphAgeMs: number;
  /** MCP server start + first tools/list timeout. */
  mcpStartupTimeoutMs: number;
  /** Per query timeout (MCP tool or CLI `affected`). */
  queryTimeoutMs: number;
  /** token_budget passed to graphify when the model omits it. */
  defaultTokenBudget: number;
  /** Upper clamp for token_budget the model may request. */
  maxTokenBudget: number;
  /** Hard cap on bytes Loam returns to the model per call (after graphify's own budget). */
  maxResultBytes: number;
  /** graphify GRAPHIFY_MAX_CONTEXTS — graphs kept warm in the server's LRU (OBSERVED default 8). */
  maxWarmGraphs: number;
  /** Optional override of the engine home (default %LOCALAPPDATA%\Loam\codegraph). */
  home?: string;
}

