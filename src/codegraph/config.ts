/** Merge a partial user config over the defaults, clamping numbers to safe ranges. */
export function resolveCodeGraphConfig(partial: Partial<CodeGraphConfig> | undefined): CodeGraphConfig {
  const c = { ...CODEGRAPH_DEFAULTS, ...(partial ?? {}) };
  const clamp = (v: number, lo: number, hi: number, d: number): number =>
    Number.isFinite(v) ? Math.min(Math.max(Math.trunc(v), lo), hi) : d;
  return {
    ...c,
    denyRoots: Array.isArray(c.denyRoots) ? c.denyRoots.filter((s) => typeof s === "string") : [],
    extraExcludes: Array.isArray(c.extraExcludes) ? c.extraExcludes.filter((s) => typeof s === "string" && s.trim() !== "") : [],
    maxCodeFileBytes: clamp(c.maxCodeFileBytes, 50_000, 20_000_000, CODEGRAPH_DEFAULTS.maxCodeFileBytes),
    maxCodeFiles: clamp(c.maxCodeFiles, 100, 200_000, CODEGRAPH_DEFAULTS.maxCodeFiles),
    maxWorkers: clamp(c.maxWorkers, 1, 16, CODEGRAPH_DEFAULTS.maxWorkers),
    indexTimeoutMs: clamp(c.indexTimeoutMs, 60_000, 7_200_000, CODEGRAPH_DEFAULTS.indexTimeoutMs),
    refreshDebounceMs: clamp(c.refreshDebounceMs, 2_000, 600_000, CODEGRAPH_DEFAULTS.refreshDebounceMs),
    maxGraphAgeMs: clamp(c.maxGraphAgeMs, 60_000, 30 * 24 * 3_600_000, CODEGRAPH_DEFAULTS.maxGraphAgeMs),
    mcpStartupTimeoutMs: clamp(c.mcpStartupTimeoutMs, 5_000, 300_000, CODEGRAPH_DEFAULTS.mcpStartupTimeoutMs),
    queryTimeoutMs: clamp(c.queryTimeoutMs, 2_000, 300_000, CODEGRAPH_DEFAULTS.queryTimeoutMs),
    defaultTokenBudget: clamp(c.defaultTokenBudget, 200, 50_000, CODEGRAPH_DEFAULTS.defaultTokenBudget),
    maxTokenBudget: clamp(c.maxTokenBudget, 500, 50_000, CODEGRAPH_DEFAULTS.maxTokenBudget),
    maxResultBytes: clamp(c.maxResultBytes, 4_096, 2 * 1024 * 1024, CODEGRAPH_DEFAULTS.maxResultBytes),
    maxWarmGraphs: clamp(c.maxWarmGraphs, 1, 32, CODEGRAPH_DEFAULTS.maxWarmGraphs),
  };
}
